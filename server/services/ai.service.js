import { GoogleGenAI } from '@google/genai'
import { z } from 'zod'
//import puppeteer from 'puppeteer'

let ai
const getAI = () => (ai ??= new GoogleGenAI({ apiKey: process.env.GOOGLE_GENAI_API_KEY }))

const MODEL = 'gemini-3-flash-preview'

const interviewReportSchema = z.object({
  matchScore: z.number().describe("A score between 0 and 100 indicating how well the candidate's profile matches the job description"),
  technicalQuestions: z.array(z.object({
    question: z.string().describe('The technical question that can be asked in the interview'),
    intention: z.string().describe('The intention of the interviewer behind asking this question'),
    answer: z.string().describe('How to answer this question, what points to cover, what approach to take etc.'),
  })).describe('Technical questions that can be asked in the interview along with their intention and how to answer them'),

  behavioralQuestions: z.array(z.object({
    question: z.string().describe('The behavioral question that can be asked in the interview'),
    intention: z.string().describe('The intention of the interviewer behind asking this question'),
    answer: z.string().describe('How to answer this question, what points to cover, what approach to take etc.'),
  })).describe('Behavioral questions that can be asked in the interview along with their intention and how to answer them'),

  skillGaps: z.array(z.object({
    skill: z.string().describe('The skill which the candidate is lacking'),
    severity: z.enum(['low', 'medium', 'high']).describe("How important this skill is for the job and how much it can impact the candidate's chances"),
  })).describe("List of skill gaps in the candidate's profile along with their severity"),

  preparationPlan: z.array(z.object({
    day: z.number().describe('The day number in the preparation plan, starting from 1'),
    focus: z.string().describe('The main focus of this day, e.g. data structures, system design, mock interviews etc.'),
    tasks: z.array(z.string()).describe('Tasks to be done on this day, e.g. solve a set of problems, watch a video etc.'),
  })).describe('A day-wise preparation plan for the candidate to prepare for the interview'),

  title: z.string().describe('The title of the job for which the interview report is generated'),
})

// Gemini busy (503) ya rate limit (429) par thodi der baad dobara try karta hai
export async function generateWithRetry(params, retries = 3) {
  for (let i = 0; i < retries; i++) {
    try {
      return await getAI().models.generateContent(params)
    } catch (err) {
      const busy = err.status === 503 || err.status === 429
      if (!busy || i === retries - 1) throw err
      await new Promise((r) => setTimeout(r, 2000 * (i + 1)))
    }
  }
}

export async function generateInterviewReport({ resume, selfDescription, jobDescription }) {
  const prompt = `Generate an interview report for the candidate below.
Return JSON with exactly these keys: title, matchScore, technicalQuestions, behavioralQuestions, skillGaps, preparationPlan.

Resume: ${resume}
Self Description: ${selfDescription}
Job Description: ${jobDescription}`

  const response = await generateWithRetry({
    model: MODEL,
    contents: prompt,
    config: {
      responseMimeType: 'application/json',
      responseJsonSchema: z.toJSONSchema(interviewReportSchema),
    },
  })

  return JSON.parse(response.text)
}

async function generatePdfFromHtml(htmlContent) {
  const { default: puppeteer } = await import('puppeteer')
  const browser = await puppeteer.launch({
  
    headless: true,
    args: ['--no-sandbox', '--disable-setuid-sandbox'], // Docker/Render par zaroori
  })

  try {
    const page = await browser.newPage()
    await page.setContent(htmlContent, { waitUntil: 'networkidle0' })

    return await page.pdf({
      format: 'A4',
      margin: { top: '20mm', bottom: '20mm', left: '15mm', right: '15mm' },
    })
  } finally {
    await browser.close()   // error aaye tab bhi browser band hoga
  }
}

export async function generateResumePdf({ resume, selfDescription, jobDescription }) {
  const resumePdfSchema = z.object({
    html: z.string().describe('The HTML content of the resume which can be converted to PDF using puppeteer'),
  })

  const prompt = `Generate resume for a candidate with the following details:
Resume: ${resume}
Self Description: ${selfDescription}
Job Description: ${jobDescription}

The response should be a JSON object with a single field "html" which contains the HTML content of the resume which can be converted to PDF using any library like puppeteer.
The resume should be tailored for the given job description and should highlight the candidate's strengths and relevant experience. The HTML content should be well-formatted and structured, making it easy to read and visually appealing.
The content of the resume should not sound like it is generated by AI and should be as close as possible to a real human-written resume.
You can highlight the content using some colors or different font styles but the overall design should be simple and professional.
The content should be ATS friendly, i.e. it should be easily parsable by ATS systems without losing important information.
The resume should not be lengthy, it should ideally be 1-2 pages long when converted to PDF. Focus on quality rather than quantity and include all the relevant information that can increase the candidate's chances of getting an interview call for the given job description.`

  const response = await generateWithRetry({
    model: MODEL,
    contents: prompt,
    config: {
      responseMimeType: 'application/json',
      responseJsonSchema: z.toJSONSchema(resumePdfSchema),   // pehle zodToJsonSchema tha (defined nahi tha)
    },
  })

  const jsonContent = JSON.parse(response.text)
  return await generatePdfFromHtml(jsonContent.html)
}

export async function evaluateAnswer({ question, answer }) {
  const prompt = `
You are a strict but friendly interviewer.
Question: ${question}
Candidate's answer: ${answer}

Evaluate the answer. Return ONLY valid JSON in this format:
{
  "score": <number from 0 to 10>,
  "strengths": ["point 1", "point 2"],
  "improvements": ["point 1", "point 2"],
  "betterAnswer": "a short improved sample answer"
}`

  const response = await generateWithRetry({
    model: MODEL,
    contents: prompt,
    config: { responseMimeType: 'application/json' },
  })

  return JSON.parse(response.text)
}
